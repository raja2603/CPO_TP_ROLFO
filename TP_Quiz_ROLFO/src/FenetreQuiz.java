    private void btnSuivantActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSuivantActionPerformed
        // TODO add your handling code here:
        indexQuestionCourante++;
        if (indexQuestionCourante < listeQuestions.size()) {
            afficherQuestionCourante();
        } else {
            question.setText("T'as enfin fini!");
            if (score == listeQuestions.size()){
                vicoire v = new vicoire();
                v.setVisible(true);
                this.dispose();
            } else {
                reponse.setText("Score final : " + score + " / " + listeQuestions.size() + " Méprisable ");
            }           
            choix1.setEnabled(false);
            choix2.setEnabled(false);
            choix3.setEnabled(false);
            choix4.setEnabled(false);
            btnSuivant.setEnabled(false); // on désactive le bouton 'suivant'
        }
    }//GEN-LAST:event_btnSuivantActionPerformed

