    private void afficherQuestionCourante() {
        if (indexQuestionCourante < listeQuestions.size()) {
            Question q = listeQuestions.get(indexQuestionCourante);
        question.setText(q.getIntitule());
        choix1.setText(q.getProposition1());
        choix2.setText(q.getProposition2());
        choix3.setText(q.getProposition3());
        choix4.setText(q.getProposition4());
        reponse.setText(""); // Efface le message de feedback
        choix1.setEnabled(true);
        choix2.setEnabled(true);
        choix3.setEnabled(true);
        choix4.setEnabled(true);
        }
    }
    private final String[] mauvaisereponse = {
    "Non",
    "Raté",
    "T'es un raté",
    "Pfffffff..",
    "ça deviens lourd là..."
    };
    private void verifierReponse(int choixUtilisateur) {
        Question q = listeQuestions.get(indexQuestionCourante);
        
        if (choixUtilisateur == q.getIndexBonneReponse()) {
            reponse.setText("Ha bah bravo.");
            score++;
        } else {
            // Génère un indice au hasard entre 0 et la longueur de mauvaisereponse
            int randomIndex = (int)(Math.random() * mauvaisereponse.length);
            reponse.setText(mauvaisereponse[randomIndex]);
        }
        // On désactive les boutons pour empêcher un 2e clic
        choix1.setEnabled(false);
        choix2.setEnabled(false);
        choix3.setEnabled(false);
        choix4.setEnabled(false);
    }
        
